#!/usr/bin/env python3
"""Regenerates src/gateway_api/*.rs from the official Gateway API CRDs.

Usage (from the repo root, with kopium installed: cargo install kopium --locked):

    python crates/ferry-controller/gen/gateway_api.py v1.6.3

It downloads the standard-channel bundle of that release, runs kopium on each
CRD Ferry watches, and post-processes the output:

- every enum gains a `#[serde(other)] Unknown` variant, so a value added by a
  newer Gateway API release fails one field instead of the whole watch list;
- the kopium prelude module is replaced by imports from `super::prelude`.

The CRD bundle itself is written to deploy/helm/ferry/crds/gateway-api.yaml
only when --crds is passed (the chart ships it as an optional dependency).
"""

import pathlib
import re
import subprocess
import sys
import tempfile
import urllib.request

ROOT = pathlib.Path(__file__).resolve().parents[3]
OUT = ROOT / "crates" / "ferry-controller" / "src" / "gateway_api"
URL = "https://github.com/kubernetes-sigs/gateway-api/releases/download/{v}/standard-install.yaml"

# (CRD plural, API version Ferry reads, output module).
# ReferenceGrant stays on v1beta1: it is served by every release Ferry
# supports, while v1 only exists from v1.5.
CRDS = [
    ("gatewayclasses", "v1", "gatewayclasses"),
    ("gateways", "v1", "gateways"),
    ("httproutes", "v1", "httproutes"),
    ("grpcroutes", "v1", "grpcroutes"),
    ("referencegrants", "v1beta1", "referencegrants"),
]


def split(bundle: str) -> dict[str, str]:
    out = {}
    for doc in bundle.split("\n---\n"):
        if "kind: CustomResourceDefinition" not in doc:
            continue
        m = re.search(r"^  name: (\w+)\.gateway\.networking\.k8s\.io$", doc, re.M)
        if m:
            out[m.group(1)] = doc.strip() + "\n"
    return out


def postprocess(code: str, version: str) -> str:
    # Drop kopium's prelude module; mod.rs provides one.
    code = re.sub(r"#\[allow\(unused_imports\)\]\nmod prelude \{.*?\n\}\n\nuse self::prelude::\*;\n",
                  "use super::prelude::*;\n", code, flags=re.S)
    code = re.sub(r"^// kopium command: .*\n", "", code, flags=re.M)
    code = re.sub(r"^// WARNING: generated by kopium.*\n",
                  f"// Generated by crates/ferry-controller/gen/gateway_api.py from Gateway API {version}.\n"
                  "// Do not edit by hand.\n", code, flags=re.M)

    def add_unknown(m: re.Match) -> str:
        body = m.group(2)
        return (f"{m.group(1)}{body}    /// A value this version of Ferry does not know.\n"
                "    #[serde(other)]\n    Unknown,\n}")

    return re.sub(r"(pub enum \w+ \{\n)(.*?)\}", add_unknown, code, flags=re.S)


def main() -> None:
    version = sys.argv[1] if len(sys.argv) > 1 else "v1.6.3"
    with urllib.request.urlopen(URL.format(v=version)) as r:
        bundle = r.read().decode("utf-8")
    crds = split(bundle)
    OUT.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory() as tmp:
        for plural, api_version, module in CRDS:
            path = pathlib.Path(tmp) / f"{plural}.yaml"
            path.write_text(crds[plural], encoding="utf-8", newline="\n")
            code = subprocess.run(
                ["kopium", "-f", str(path), "--api-version", api_version,
                 "--derive", "Default", "--derive", "PartialEq", "--smart-derive-elision"],
                check=True, capture_output=True, text=True, encoding="utf-8",
            ).stdout
            (OUT / f"{module}.rs").write_text(postprocess(code, version), encoding="utf-8", newline="\n")
            print(f"wrote {module}.rs ({plural} {api_version})")
    subprocess.run(["rustfmt", "--edition", "2024", *map(str, OUT.glob("*.rs"))], check=True)
    if "--crds" in sys.argv:
        dest = ROOT / "deploy" / "helm" / "ferry" / "crds" / "gateway-api.yaml"
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_text(bundle, encoding="utf-8", newline="\n")
        print(f"wrote {dest}")


if __name__ == "__main__":
    main()
